type PHPExtensionStatus struct {
	Key       string `json:"key"`
	Label     string `json:"label"`
	Version   string `json:"version"`
	Installed bool   `json:"installed"`
	ReadOnly  bool   `json:"readOnly"`
}

type MalwareScanResult struct {
	SiteID        string   `json:"siteId"`
	Path          string   `json:"path"`
	Status        string   `json:"status"`
	InfectedFiles []string `json:"infectedFiles"`
	Output        string   `json:"output"`
}

var manageablePHPExtensions = []struct{ key, label string }{
	{"bcmath", "BCMath"}, {"gmp", "GMP"}, {"imap", "IMAP"}, {"intl", "Intl"},
	{"soap", "SOAP"}, {"zip", "ZIP"}, {"redis", "Redis"},
}

var safeHostnamePattern = regexp.MustCompile(`^(?i:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)*)$`)

func (s *System) WAFEngine() string {
	if s.demo {
		return "ModSecurity + OWASP CRS"
	}
	for _, path := range []string{
		"/usr/lib/nginx/modules/ngx_http_modsecurity_module.so",
		"/usr/lib64/nginx/modules/ngx_http_modsecurity_module.so",
		"/etc/nginx/modules/ngx_http_modsecurity_module.so",
	} {
		if _, err := os.Stat(path); err == nil {
			if _, err := os.Stat("/etc/litecp/waf/crs-setup.conf"); err == nil {
				return "ModSecurity + OWASP CRS"
			}
		}
	}
	return "not installed"
}

func (s *System) wafRules(site Site, mode string) string {
	engineMode := "On"
	if mode == "detect" {
		engineMode = "DetectionOnly"
	}
	return fmt.Sprintf(`# Generated by LiteCP. Per-site ModSecurity policy.
Include /etc/litecp/waf/modsecurity.conf
SecRuleEngine %s
SecAuditLog /var/log/nginx/litecp-waf-%s.log
Include /etc/litecp/waf/crs-setup.conf
Include /etc/litecp/waf/rules/*.conf
`, engineMode, safeSiteID(site.ID))
}

func wafBlock(site Site, mode string) string {
	if mode == "off" || mode == "" {
		return "    # LITECP_WAF_BEGIN\n    # Web application firewall is disabled.\n    # LITECP_WAF_END"
	}
	return fmt.Sprintf("    # LITECP_WAF_BEGIN\n    modsecurity on;\n    modsecurity_rules_file /etc/litecp/waf/site-%s.conf;\n    # LITECP_WAF_END", safeSiteID(site.ID))
}

func replaceWAFBlock(config string, site Site, mode string) (string, error) {
	start := strings.Index(config, "    # LITECP_WAF_BEGIN")
	endMarker := "    # LITECP_WAF_END"
	if start >= 0 {
		endRelative := strings.Index(config[start:], endMarker)
		if endRelative < 0 {
			return "", errors.New("managed WAF marker is incomplete")
		}
		end := start + endRelative + len(endMarker)
		return config[:start] + wafBlock(site, mode) + config[end:], nil
	}
	server := strings.Index(config, "server {")
	if server < 0 {
		return "", errors.New("managed Nginx server block was not found")
	}
	insert := server + len("server {")
	return config[:insert] + "\n" + wafBlock(site, mode) + config[insert:], nil
}

func (s *System) SetWAFMode(ctx context.Context, site Site, mode string) error {
	mode = strings.ToLower(strings.TrimSpace(mode))
	if mode != "off" && mode != "detect" && mode != "block" {
		return errors.New("WAF mode must be off, detect or block")
	}
	if mode != "off" && s.WAFEngine() == "not installed" {
		return errors.New("ModSecurity with OWASP CRS is not installed; rerun the LiteCP installer with WAF support")
	}
	if s.demo {
		return nil
	}
	configPath, _ := s.nginxPaths(site.Domain)
	original, err := os.ReadFile(configPath)
	if err != nil {
		return fmt.Errorf("read Nginx configuration: %w", err)
	}
	updated, err := replaceWAFBlock(string(original), site, mode)
	if err != nil {
		return err
	}
	rulePath := filepath.Join("/etc/litecp/waf", "site-"+safeSiteID(site.ID)+".conf")
	oldRules, rulesErr := os.ReadFile(rulePath)
	if rulesErr != nil && !errors.Is(rulesErr, os.ErrNotExist) {
		return rulesErr
	}
	restoreRules := func() {
		if rulesErr == nil {
			_ = writeAtomic(rulePath, oldRules, 0640)
		} else {
			_ = os.Remove(rulePath)
		}
	}
	if mode != "off" {
		if err := writeAtomic(rulePath, []byte(s.wafRules(site, mode)), 0640); err != nil {
			return err
		}
	}
	rollback := func() {
		restoreRules()
		_ = writeAtomic(configPath, original, 0644)
		_, _ = runCommand(context.Background(), 15*time.Second, "systemctl", "reload", "nginx")
	}
	if err := writeAtomic(configPath, []byte(updated), 0644); err != nil {
		restoreRules()
		return err
	}
	if _, err := runCommand(ctx, 15*time.Second, "nginx", "-t"); err != nil {
		rollback()
		return err
	}
	if _, err := runCommand(ctx, 15*time.Second, "systemctl", "reload", "nginx"); err != nil {
		rollback()
		return err
	}
	if mode == "off" {
		_ = os.Remove(rulePath)
	}
	return nil
}

func (s *System) PHPExtensions(ctx context.Context) ([]PHPExtensionStatus, error) {
	result := []PHPExtensionStatus{}
	for _, version := range s.installedPHPVersions() {
		modules := map[string]bool{}
		if s.demo {
			for _, item := range manageablePHPExtensions {
				modules[item.key] = item.key != "redis"
			}
		} else {
			output, err := runCommand(ctx, 15*time.Second, s.phpBinary(version), "-m")
			if err != nil {
				return nil, fmt.Errorf("read PHP %s modules: %w", version, err)
			}
			for _, line := range strings.Split(strings.ToLower(output), "\n") {
				modules[strings.TrimSpace(line)] = true
			}
		}
		for _, item := range manageablePHPExtensions {
			result = append(result, PHPExtensionStatus{Key: item.key, Label: item.label, Version: version, Installed: modules[item.key], ReadOnly: s.usesPHP73Container(version)})
		}
	}
	return result, nil
}

func (s *System) phpExtensionPackages(version, extension string) []string {
	if s.os.ID == "ubuntu" || s.os.ID == "debian" {
		return []string{"php" + version + "-" + extension}
	}
	prefix := "php" + strings.ReplaceAll(version, ".", "") + "-php-"
	switch extension {
	case "zip":
		return []string{prefix + "pecl-zip", prefix + "zip"}
	case "imap":
		return []string{prefix + "imap", prefix + "pecl-imap"}
	case "redis":
		return []string{prefix + "pecl-redis6", prefix + "pecl-redis5", prefix + "pecl-redis"}
	default:
		return []string{prefix + extension}
	}
}

func extensionAllowed(extension string) bool {
	for _, item := range manageablePHPExtensions {
		if item.key == extension {
			return true
		}
	}
	return false
}

func (s *System) packageInstalled(ctx context.Context, name string) bool {
	if s.os.ID == "ubuntu" || s.os.ID == "debian" {
		output, err := runCommand(ctx, 10*time.Second, "dpkg-query", "-W", "-f=${Status}", name)
		return err == nil && strings.TrimSpace(output) == "install ok installed"
	}
	_, err := runCommand(ctx, 10*time.Second, "rpm", "-q", name)
	return err == nil
}

func (s *System) packageAvailable(ctx context.Context, name string) bool {
	if s.os.ID == "ubuntu" || s.os.ID == "debian" {
		return true
	}
	output, err := runCommand(ctx, 30*time.Second, "dnf", "-q", "repoquery", "--available", name)
	return err == nil && strings.TrimSpace(output) != ""
}

func (s *System) phpExtensionLoaded(ctx context.Context, version, extension string) (bool, error) {
	output, err := runCommand(ctx, 20*time.Second, s.phpBinary(version), "-m")
	if err != nil {
		return false, err
	}
	for _, module := range strings.Fields(strings.ToLower(output)) {
		if module == extension {
			return true, nil
		}
	}
	return false, nil
}

func (s *System) SetPHPExtension(ctx context.Context, version, extension string, install bool) error {
	version, extension = strings.TrimSpace(version), strings.ToLower(strings.TrimSpace(extension))
	if !containsString(supportedPHPVersions, version) || !s.phpRuntimeAvailable(version) {
		return errors.New("selected PHP version is not installed")
	}
	if !extensionAllowed(extension) {
		return errors.New("extension is not in LiteCP's reviewed package allowlist")
	}
	if s.usesPHP73Container(version) {
		return errors.New("PHP 7.3 compatibility extensions are immutable; rebuild the compatibility image to change them")
	}
	if s.demo {
		return nil
	}
	packages := s.phpExtensionPackages(version, extension)
	selected := ""
	if install {
		for _, candidate := range packages {
			if s.packageInstalled(ctx, candidate) || s.packageAvailable(ctx, candidate) {
				selected = candidate
				break
			}
		}
		if selected == "" {
			return errors.New("no compatible package is available for that PHP extension")
		}
	} else {
		for _, candidate := range packages {
			if s.packageInstalled(ctx, candidate) {
				selected = candidate
				break
			}
		}
		if selected == "" {
			return nil
		}
	}
	wasInstalled := s.packageInstalled(ctx, selected)
	var args []string
	if s.os.ID == "ubuntu" || s.os.ID == "debian" {
		args = []string{"dpkg", "--remove", selected}
		if install {
			args = []string{"apt-get", "install", "--no-remove", "--no-install-recommends", "-y", selected}
		}
	} else {
		args = []string{"rpm", "-e", selected}
		if install {
			args = []string{"dnf", "install", "--setopt=install_weak_deps=False", "-y", selected}
		}
	}
	// Native removal refuses dependency breakage instead of cascading to PHP/FPM.
	if _, err := runHostCommand(ctx, 10*time.Minute, args[0], args[1:]...); err != nil {
		return err
	}
	unit := s.phpUnitForVersion(version)
	rollback := func() error {
		// Do not remove a package which pre-dated this request. A failed removal
		// is restored with the same reviewed package name.
		if install && wasInstalled {
			_, restartErr := runCommand(context.Background(), 45*time.Second, "systemctl", "restart", unit)
			return restartErr
		}
		var rollbackArgs []string
		if s.os.ID == "ubuntu" || s.os.ID == "debian" {
			rollbackArgs = []string{"apt-get", "install", "--no-remove", "--no-install-recommends", "-y", selected}
			if install {
				rollbackArgs = []string{"dpkg", "--remove", selected}
			}
		} else {
			rollbackArgs = []string{"dnf", "install", "--setopt=install_weak_deps=False", "-y", selected}
			if install {
				rollbackArgs = []string{"rpm", "-e", selected}
			}
		}
		if _, rollbackErr := runHostCommand(context.Background(), 10*time.Minute, rollbackArgs[0], rollbackArgs[1:]...); rollbackErr != nil {
			return rollbackErr
		}
		_, restartErr := runCommand(context.Background(), 45*time.Second, "systemctl", "restart", unit)
		return restartErr
	}
	if _, err := runCommand(ctx, 45*time.Second, "systemctl", "restart", unit); err != nil {
		return fmt.Errorf("PHP-FPM restart failed after package change: %v (rollback: %v)", err, rollback())
	}
	loaded, err := s.phpExtensionLoaded(ctx, version, extension)
	if err != nil || loaded != install {
		verificationErr := err
		if verificationErr == nil {
			verificationErr = fmt.Errorf("extension state is %t after requesting %t", loaded, install)
		}
		return fmt.Errorf("PHP extension verification failed: %v (rollback: %v)", verificationErr, rollback())
	}
	return nil
}

func (s *System) AntivirusAvailable() bool {
	if s.demo {
		return true
	}
	_, err := exec.LookPath("clamscan")
	return err == nil
}

func (s *System) ScanManagedPath(ctx context.Context, site Site, relative string) (MalwareScanResult, error) {
	if !s.AntivirusAvailable() {
		return MalwareScanResult{}, errors.New("ClamAV is not installed; rerun the LiteCP installer with antivirus support")
	}
	target, clean, err := resolveManagedPath(site.Root, relative, false)
	if err != nil {
		return MalwareScanResult{}, err
	}
	result := MalwareScanResult{SiteID: site.ID, Path: clean, Status: "clean", InfectedFiles: []string{}}
	if s.demo {
		result.Output = "Known viruses: demo signatures current"
		return result, nil
	}
	commandCtx, cancel := context.WithTimeout(ctx, 30*time.Minute)
	defer cancel()
	if site.RuntimeUID < 1 || site.RuntimeGID < 1 {
		return result, errors.New("site runtime identity is not configured")
	}
	command := exec.CommandContext(commandCtx, "setpriv", fmt.Sprintf("--reuid=%d", site.RuntimeUID), fmt.Sprintf("--regid=%d", site.RuntimeGID), "--clear-groups", "clamscan", "--recursive=yes", "--infected", "--follow-dir-symlinks=0", "--follow-file-symlinks=0", "--max-filesize=256M", "--max-scansize=2G", target)
	var output limitedBuffer
	command.Stdout, command.Stderr = &output, &output
	err = command.Run()
	text := output.String()
	if len(text) > 1<<20 {
		text = text[len(text)-(1<<20):]
	}
	result.Output = strings.TrimSpace(text)
	if err != nil {
		var exitErr *exec.ExitError
		if !errors.As(err, &exitErr) || exitErr.ExitCode() != 1 {
			return MalwareScanResult{}, fmt.Errorf("ClamAV scan failed: %s", strings.TrimSpace(text))
		}
		result.Status = "infected"
		for _, line := range strings.Split(text, "\n") {
			if !strings.HasSuffix(strings.TrimSpace(line), " FOUND") {
				continue
			}
			name := strings.TrimSpace(strings.SplitN(line, ":", 2)[0])
			if relativeName, relErr := filepath.Rel(site.Root, name); relErr == nil && pathWithinRoot(site.Root, name) {
				result.InfectedFiles = append(result.InfectedFiles, filepath.ToSlash(relativeName))
			}
		}
	}
	return result, nil
}

func validateResolvers(values []string) ([]string, error) {
	if len(values) < 1 || len(values) > 4 {
		return nil, errors.New("configure between one and four DNS resolvers")
	}
	result, seen := []string{}, map[string]bool{}
	for _, value := range values {
		ip := net.ParseIP(strings.TrimSpace(value))
		if ip == nil || ip.IsUnspecified() || ip.IsMulticast() {
			return nil, errors.New("resolver addresses must be valid unicast IP addresses")
		}
		canonical := ip.String()
		if !seen[canonical] {
			seen[canonical] = true
			result = append(result, canonical)
		}
	}
	return result, nil
}

func (s *System) SetResolvers(ctx context.Context, values []string) error {
	resolvers, err := validateResolvers(values)
	if err != nil {
		return err
	}
	if s.demo {
		return nil
	}
	_, err = runHostCommand(ctx, 2*time.Minute, "/usr/local/bin/litecp", append([]string{"host-resolvers"}, resolvers...)...)
	return err
}

func (s *System) SetHostname(ctx context.Context, hostname string) error {
	hostname = strings.ToLower(strings.TrimSpace(hostname))
	if len(hostname) > 253 || !safeHostnamePattern.MatchString(hostname) {
		return errors.New("enter a valid hostname or fully-qualified domain name")
	}
	if s.demo {
		return nil
	}
	_, err := runCommand(ctx, 30*time.Second, "hostnamectl", "set-hostname", hostname)
	return err
}

func (s *System) ScheduleReboot(ctx context.Context) error {
	if s.demo {
		return nil
	}
	_, err := runCommand(ctx, 15*time.Second, "systemd-run", "--unit=litecp-reboot", "--on-active=5s", "systemctl", "reboot")
	return err
}

func (a *App) activities(w http.ResponseWriter, r *http.Request) {
	page, _ := strconv.Atoi(r.URL.Query().Get("page"))
	perPage, _ := strconv.Atoi(r.URL.Query().Get("perPage"))
	if page < 1 {
		page = 1
	}
	if perPage < 1 {
		perPage = 5
	}
	if perPage > 100 {
		perPage = 100
	}
	items, total := a.store.Activities(page, perPage)
	writeJSON(w, http.StatusOK, map[string]any{"items": items, "page": page, "perPage": perPage, "total": total, "pages": (total + perPage - 1) / perPage})
}

func (a *App) phpExtensions(w http.ResponseWriter, r *http.Request) {
	if r.Method == http.MethodGet {
		items, err := a.system.PHPExtensions(r.Context())
		if err != nil {
			writeError(w, http.StatusBadGateway, err.Error())
			return
		}
		writeJSON(w, http.StatusOK, map[string]any{"extensions": items})
		return
	}
	if r.Method != http.MethodPut {
		w.Header().Set("Allow", "GET, PUT")
		writeError(w, http.StatusMethodNotAllowed, "Method not allowed.")
		return
	}
	var input struct {
		Version, Extension string
		Installed          bool
	}
	if err := decodeJSON(r, &input); err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	if err := a.system.SetPHPExtension(r.Context(), input.Version, input.Extension, input.Installed); err != nil {
		writeError(w, http.StatusBadGateway, err.Error())
		return
	}
	action := "removed"
	if input.Installed {
		action = "installed"
	}
	a.store.AddActivity("PHP extension "+action, fmt.Sprintf("PHP %s: %s", input.Version, input.Extension), "success")
	writeJSON(w, http.StatusOK, map[string]bool{"ok": true})
}

func (a *App) malwareScan(w http.ResponseWriter, r *http.Request) {
	var input struct{ SiteID, Path string }
	if err := decodeJSON(r, &input); err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	site := a.store.SiteByID(input.SiteID)
	if site == nil {
		writeError(w, http.StatusNotFound, "Website not found.")
		return
	}
	result, err := a.system.ScanManagedPath(r.Context(), *site, input.Path)
	if err != nil {
		writeError(w, http.StatusBadGateway, err.Error())
		return
	}
	kind := "success"
	if result.Status == "infected" {
		kind = "warning"
	}
	a.store.AddActivity("Malware scan "+result.Status, site.Domain+": "+input.Path, kind)
	writeJSON(w, http.StatusOK, result)
}

func (a *App) setSiteWAF(w http.ResponseWriter, r *http.Request) {
	var input struct{ ID, Mode string }
	if err := decodeJSON(r, &input); err != nil {
		writeError(w, http.StatusBadRequest, err.Error())
		return
	}
	site := a.store.SiteByID(input.ID)
	if site == nil {
		writeError(w, http.StatusNotFound, "Website not found.")
		return
	}
	original := site.WAFMode
	if original == "" {
		original = "off"
	}
	mode := strings.ToLower(strings.TrimSpace(input.Mode))
	if err := a.system.SetWAFMode(r.Context(), *site, mode); err != nil {
		writeError(w, http.StatusBadGateway, err.Error())
		return
	}
	if err := a.store.UpdateSite(site.ID, func(value *Site) { value.WAFMode = mode }); err != nil {
		_ = a.system.SetWAFMode(context.Background(), *site, original)
		writeError(w, http.StatusInternalServerError, "WAF change was rolled back because panel state could not be saved.")
		return
	}
	a.store.AddActivity("Website WAF updated", site.Domain+": "+mode, "success")
	writeJSON(w, http.StatusOK, map[string]bool{"ok": true})
}

